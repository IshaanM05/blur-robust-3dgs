"""Collect all results/*/*/*/metrics.json into docs/results.md and results/all_results.csv."""
import csv, json
from pathlib import Path

rows = []
for f in sorted(Path("results").glob("*/*/*/metrics.json")):
    scene, tag, method = f.parts[1], f.parts[2], f.parts[3]
    m = json.load(open(f))
    rows.append({"scene": scene, "setting": tag, "method": method, "psnr": m["psnr"], "ssim": m["ssim"], "lpips": m["lpips"],
                 "kernel_l2": m.get("kernel_best_shift_l2", ""), "n_gaussians": m.get("n_gaussians", ""), "seconds": round(m.get("train_seconds", 0))})
if rows:
    with open("results/all_results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)
out = ["# All results (held-out sharp views; auto-generated by scripts/collect.py)\n"]
for key in sorted({(r["scene"], r["setting"]) for r in rows}):
    out.append(f"\n## {key[0]} / {key[1]}\n\n| method | PSNR | SSIM | LPIPS | kernel L2 | #Gaussians |\n|---|---|---|---|---|---|")
    for r in sorted((r for r in rows if (r["scene"], r["setting"]) == key), key=lambda r: -r["psnr"]):
        kl = f"{r['kernel_l2']:.3f}" if r["kernel_l2"] != "" else "-"
        out.append(f"| {r['method']} | {r['psnr']:.2f} | {r['ssim']:.3f} | {r['lpips']:.3f} | {kl} | {r['n_gaussians']} |")
Path("docs/results.md").write_text("\n".join(out) + "\n")
print(f"{len(rows)} runs collected -> docs/results.md")
